#ifndef CHIPYARD_RTA_V4_H
#define CHIPYARD_RTA_V4_H

#include <stdint.h>

#ifndef RTA_V4_BASE
#define RTA_V4_BASE ((uintptr_t)0x10050000UL)
#endif

#define RTA_V4_DEVICE_ID       0x000
#define RTA_V4_ABI_VERSION     0x008
#define RTA_V4_CAPABILITIES    0x010
#define RTA_V4_BITSTREAM_BITS  0x018
#define RTA_V4_LAYOUT_HASH     0x020
#define RTA_V4_SCRATCH         0x060

#define RTA_V4_CONFIG_COMMAND  0x080
#define RTA_V4_CONFIG_STATUS   0x088
#define RTA_V4_CONFIG_DATA     0x090
#define RTA_V4_CONFIG_BITS_IN  0x098
#define RTA_V4_CONFIG_BITS_OUT 0x0a0
#define RTA_V4_CONFIG_ERROR    0x0a8

#define RTA_V4_COMPUTE_CONTROL 0x0c0
#define RTA_V4_COMPUTE_STATUS  0x0c8
#define RTA_V4_SNAPSHOT_SEQ    0x0d0
#define RTA_V4_COMPUTE_ERROR   0x0d8

#define RTA_V4_WEST_INPUT(n)   (0x100 + 8 * (n))
#define RTA_V4_NORTH_INPUT(n)  (0x120 + 8 * (n))
#define RTA_V4_EAST_OUTPUT(n)  (0x140 + 8 * (n))
#define RTA_V4_SOUTH_OUTPUT(n) (0x160 + 8 * (n))
#define RTA_V4_ACTIVITY        0x180

#define RTA_V4_ID_VALUE          UINT32_C(0x52544134)
#define RTA_V4_ABI_VERSION_VALUE UINT32_C(0x00010000)
#define RTA_V4_CAPABILITIES_VALUE UINT32_C(0x12080404)
#define RTA_V4_SCAN_BITS         UINT32_C(3140)
#define RTA_V4_SCAN_WORDS        UINT32_C(99)

#define RTA_V4_CAP_ROWS_SHIFT       0
#define RTA_V4_CAP_COLUMNS_SHIFT    8
#define RTA_V4_CAP_DATA_WIDTH_SHIFT 16
#define RTA_V4_CAP_PLANES_SHIFT     24
#define RTA_V4_CAP_PRED_WIDTH_SHIFT 28
#define RTA_V4_CAP_BYTE_MASK         UINT32_C(0xff)
#define RTA_V4_CAP_NIBBLE_MASK       UINT32_C(0xf)

#define RTA_V4_CONFIG_START UINT32_C(1)
#define RTA_V4_CONFIG_ABORT UINT32_C(2)

#define RTA_V4_CFG_STATE_MASK  UINT32_C(0x7)
#define RTA_V4_CFG_DATA_READY  (UINT32_C(1) << 3)
#define RTA_V4_CFG_BUSY        (UINT32_C(1) << 4)
#define RTA_V4_CFG_CONFIGURED  (UINT32_C(1) << 5)
#define RTA_V4_CFG_ANY_ERROR   (UINT32_C(1) << 6)
#define RTA_V4_CFG_PROG_WE_OUT (UINT32_C(1) << 7)
#define RTA_V4_CFG_PROG_DOUT   (UINT32_C(1) << 8)
#define RTA_V4_CFG_TAIL_SEEN   (UINT32_C(1) << 9)

#define RTA_V4_CFG_STATE_IDLE    UINT32_C(0)
#define RTA_V4_CFG_STATE_RESET   UINT32_C(1)
#define RTA_V4_CFG_STATE_LOAD    UINT32_C(2)
#define RTA_V4_CFG_STATE_DRAIN   UINT32_C(3)
#define RTA_V4_CFG_STATE_COMMIT  UINT32_C(4)
#define RTA_V4_CFG_STATE_READY   UINT32_C(5)
#define RTA_V4_CFG_STATE_ERROR   UINT32_C(6)
#define RTA_V4_CFG_STATE_RELEASE UINT32_C(7)

#define RTA_V4_CFG_ERR_INVALID_COMMAND (UINT32_C(1) << 0)
#define RTA_V4_CFG_ERR_UNEXPECTED_DATA (UINT32_C(1) << 1)
#define RTA_V4_CFG_ERR_BAD_PADDING     (UINT32_C(1) << 2)
#define RTA_V4_CFG_ERR_TAIL_COUNT      (UINT32_C(1) << 3)
#define RTA_V4_CFG_ERR_TAIL_TIMEOUT    (UINT32_C(1) << 4)

#define RTA_V4_COMPUTE_RESET   UINT32_C(1)
#define RTA_V4_COMPUTE_RUN     UINT32_C(2)
#define RTA_V4_COMPUTE_STEP    UINT32_C(4)
#define RTA_V4_COMPUTE_CAPTURE UINT32_C(8)

#define RTA_V4_COMPUTE_CONFIGURED    (UINT32_C(1) << 0)
#define RTA_V4_COMPUTE_RESET_ACTIVE  (UINT32_C(1) << 1)
#define RTA_V4_COMPUTE_ENABLE_ACTIVE (UINT32_C(1) << 2)
#define RTA_V4_COMPUTE_SW_RESET      (UINT32_C(1) << 3)
#define RTA_V4_COMPUTE_RUN_ACTIVE    (UINT32_C(1) << 4)
#define RTA_V4_COMPUTE_SNAPSHOT_VALID (UINT32_C(1) << 5)
#define RTA_V4_COMPUTE_ANY_ERROR     (UINT32_C(1) << 6)
#define RTA_V4_COMPUTE_INPUT_WRITABLE (UINT32_C(1) << 7)

#define RTA_V4_COMPUTE_ERR_INVALID_COMMAND    (UINT32_C(1) << 0)
#define RTA_V4_COMPUTE_ERR_STEP_WHILE_RUNNING (UINT32_C(1) << 1)
#define RTA_V4_COMPUTE_ERR_CAPTURE_WHILE_RUN  (UINT32_C(1) << 2)
#define RTA_V4_COMPUTE_ERR_INPUT_WHILE_RUN    (UINT32_C(1) << 3)
#define RTA_V4_COMPUTE_ERR_CONFLICTING_BITS   (UINT32_C(1) << 4)
#define RTA_V4_COMPUTE_ERR_PULSE_WHILE_RESET  (UINT32_C(1) << 5)

static inline uint32_t rta_v4_pack_lane(
    uint8_t data0, uint8_t data1, uint8_t predicate)
{
  return (uint32_t)data0 | ((uint32_t)data1 << 8) |
      (((uint32_t)predicate & 1U) << 16);
}

#endif
